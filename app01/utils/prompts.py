"""
提示词模板（三段式：角色 + 任务 + 输出格式）
==========================================

为什么提示词要独立成一个文件、而不是散在视图里：
  1. 提示词是本项目的"核心工艺"，集中放才好对比、好迭代；
  2. 答辩时要能当场念出某一段提示词，翻一个文件就能找到；
  3. 同一套模板四处在用（JD / 问答 / 点评 / 对话），集中维护不跑偏。

写提示词的三条经验（答辩可讲）：
  1. system 定"人设 + 边界"，user 定"这次具体做什么 + 要什么格式"；
  2. 格式写死（如"分三段，标题用【】"），模型输出才稳定，前端才好渲染；
  3. 资料问答必须写"资料里没有就说不知道"，否则模型一定会编。
"""

# ------------------------------------------------------------------
# 一、招聘 JD（T2）
# ------------------------------------------------------------------
JD_SYSTEM = (
    "你是一名有 10 年经验的资深 HR，擅长写简洁、真实、不夸张的招聘文案。"
    "你只输出 JD 正文，不寒暄、不解释、不使用 Markdown 表格。"
)


def build_jd_prompt(title, depart="", years=""):
    """
    构造 JD 的任务段。

    参数都可选：只给岗位时也能生成；补部门和经验要求会更贴合。
    输出格式写死成三段，前端就不用解析自由文本了。
    """
    extra = []
    if depart:
        extra.append(f"所属部门：{depart}")
    if years:
        extra.append(f"经验要求：{years}")
    extra_text = "；".join(extra)

    return (
        f"请为「{title}」岗位撰写一份招聘 JD。\n"
        f"{('背景信息：' + extra_text + '。') if extra_text else ''}\n"
        "严格按以下三段输出，每段标题用【】标出，不要编号、不要多余说明：\n"
        "【岗位职责】3–4 条，每条一行，以动词开头；\n"
        "【任职要求】3–4 条，含学历/技能/经验，不写性别年龄；\n"
        "【薪资范围】一行，给出一个合理区间并注明「面议可谈」。\n"
        "全文控制在 150 字左右，语言简洁，不要出现公司名称。"
    )


# ------------------------------------------------------------------
# 二、制度问答（T3）
# ------------------------------------------------------------------
QA_SYSTEM = (
    "你是企业制度助手。你只能依据用户提供的【资料】回答，"
    "资料中没有提到的内容，必须回答「不知道」，禁止用常识推测、禁止编造条款。"
    "回答控制在 3 句以内，末尾用「依据：《制度标题》」注明来源。"
)


def build_qa_prompt(question, context):
    """
    构造问答提示。

    context 是 retrieval 检索出来的若干条制度拼成的文本，
    这里用显式分隔符包起来，让模型清楚"哪部分是资料、哪部分是问题"。
    """
    return (
        "【资料】\n"
        f"{context}\n\n"
        "【问题】\n"
        f"{question}\n\n"
        "请只依据上面的资料回答。若资料不足以回答，直接输出：不知道。"
    )


# ------------------------------------------------------------------
# 三、数据点评（T4）
# ------------------------------------------------------------------
COMMENT_SYSTEM = (
    "你是 HR 数据分析助手。你只根据给出的数字做客观点评："
    "不推测原因（健康、家庭、情绪、离职倾向一律不提），不评价员工品格，不给法律意见。"
    "如果数据显示记录缺失（例如没有考勤记录），只说明缺失并要求核对补录，不要列举任何可能原因。"
    "输出一句点评加一条建议，总共不超过 50 字，不使用列表和标题。"
)


def build_comment_prompt(data_text):
    """data_text 由视图把考勤/薪资记录转成一句人话，见 views/ai.py 的 _build_data_text。"""
    return (
        f"【员工数据】\n{data_text}\n\n"
        "请写一句客观点评（说明数据反映的情况），再给一条可执行的改进建议。"
        "不要复述所有数字，只挑关键的两三个。"
    )


# ------------------------------------------------------------------
# 四、多轮对话（T5）
# ------------------------------------------------------------------
CHAT_SYSTEM = (
    "你是企业员工管理系统里的智能助手，回答简短、口语化。"
    "不要编造具体的金额、天数、审批层级；不确定时就说「建议查看制度问答或咨询 HR」，"
    "不要用「一般公司都…」这种方式杜撰规定。"
    "涉及薪资明细、他人隐私、公司机密的问题，礼貌拒答并建议走正式流程。"
    "每次回答控制在 100 字以内。"
)


def build_chat_messages(question, history=None, max_rounds=6, context=None):
    """
    组装多轮 messages。

    历史只在 session 里保留最近 max_rounds 轮（一问一答算一轮），
    超出就丢最早的 —— 目的是控制 token，避免上下文越来越长、越来越慢。

    context：检索到的制度片段。有资料时把它塞进 system，
    让对话助手也"照本宣科"，而不是编一句"一般公司都这样"。
    """
    system = CHAT_SYSTEM
    if context:
        system += (
            "\n【可参考资料】\n" + context +
            "\n回答涉及公司制度时，以上面的资料为准；资料没写的，就说不知道并建议查阅制度。"
        )
    messages = [{"role": "system", "content": system}]

    history = history or []
    keep = max_rounds * 2          # 一问一答两条
    for item in history[-keep:]:
        role = item.get("role")
        content = item.get("content")
        if role in ("user", "assistant") and content:
            messages.append({"role": role, "content": content})

    messages.append({"role": "user", "content": question})
    return messages
